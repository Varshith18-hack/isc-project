def generate_normal_reading(
    device_id: str,
    device_type: str,
    timestamp: datetime,
    battery_level: float
) -> dict:
    """
    Generate a single normal reading within standard medical and network baselines.

    Physiological & Device Parameters:
    - Heart Rate: 60.0 - 100.0 bpm (Adult resting sinus rhythm)
    - Systolic BP: 95.0 - 120.0 mmHg
    - Diastolic BP: 60.0 - 80.0 mmHg (Always strictly lower than Systolic)
    - Oxygen Saturation (SpO2): 95.0% - 100.0%
    - Body Temperature: 36.5°C - 37.4°C (Normothermia)
    - Network Packets per Minute (Activity Level): 15.0 - 45.0 packets/min
    - Battery Level: 15.0% - 100.0% (Natural discharge)
    """
    # Sample from Gaussian distributions with small natural sensor fluctuations
    heart_rate = round(float(np.random.normal(loc=75.0, scale=6.5)), 1)
    heart_rate = max(60.0, min(100.0, heart_rate))

    systolic_bp = round(float(np.random.normal(loc=115.0, scale=5.0)), 1)
    systolic_bp = max(95.0, min(125.0, systolic_bp))

    diastolic_bp = round(float(np.random.normal(loc=75.0, scale=4.0)), 1)
    # Ensure Diastolic remains clinically realistic relative to Systolic
    diastolic_bp = max(60.0, min(systolic_bp - 20.0, diastolic_bp))

    spo2 = round(float(np.random.normal(loc=98.2, scale=0.8)), 1)
    spo2 = max(95.0, min(100.0, spo2))

    temperature = round(float(np.random.normal(loc=36.95, scale=0.18)), 2)
    temperature = max(36.50, min(37.40, temperature))

    device_activity = round(float(np.random.normal(loc=26.0, scale=4.5)), 1)
    device_activity = max(15.0, min(45.0, device_activity))

    return {
        "timestamp": timestamp.strftime("%Y-%m-%d %H:%M:%S"),
        "device_id": device_id,
        "device_type": device_type,
        "heart_rate": heart_rate,
        "systolic_bp": systolic_bp,
        "diastolic_bp": diastolic_bp,
        "oxygen_saturation": spo2,
        "body_temperature": temperature,
        "device_activity_level": device_activity,
        "battery_level": round(battery_level, 1),
        "is_anomaly": 0,
        "anomaly_type": "Normal",
        "is_synthetic": True,
    }


def inject_anomaly_reading(
    device_id: str,
    device_type: str,
    timestamp: datetime,
    battery_level: float
) -> dict:
    """
    Generate an anomalous observation representing either a clinical crisis
    or a cybersecurity / hardware exploit.

    Anomaly Classes:
    1. Abnormal_Heart_Rate: Severe tachycardia (>150 bpm) or bradycardia (<48 bpm)
    2. Low_Oxygen_Saturation: Hypoxia emergency (SpO2 drops to 70% - 86%)
    3. Unusual_Temperature: High septic hyperthermia (>39.5°C) or hypothermia (<34.8°C)
    4. Network_Traffic_Burst: Denial of Service / Telemetry flood (400 - 1400 pkts/min)
    5. Device_Telemetry_Spoofing: Physically impossible sensor flatline or inverted BP
    6. Rapid_Battery_Drain: Hardware compromise, malicious loop, or sudden power drop
    """
    anomaly_scenario = random.choice([
        "Abnormal_Heart_Rate",
        "Low_Oxygen_Saturation",
        "Unusual_Temperature",
        "Network_Traffic_Burst",
        "Device_Telemetry_Spoofing",
        "Rapid_Battery_Drain",
    ])

    # Start with base normal structure
    reading = generate_normal_reading(device_id, device_type, timestamp, battery_level)
    reading["is_anomaly"] = 1
    reading["anomaly_type"] = anomaly_scenario

    if anomaly_scenario == "Abnormal_Heart_Rate":
        # Sub-scenarios: Severe Tachycardia (80% chance) or Critical Bradycardia (20% chance)
        if random.random() < 0.8:
            reading["heart_rate"] = round(float(np.random.uniform(145.0, 198.0)), 1)
            reading["systolic_bp"] = round(float(np.random.uniform(150.0, 205.0)), 1)
            reading["diastolic_bp"] = round(float(np.random.uniform(95.0, 125.0)), 1)
        else:
            reading["heart_rate"] = round(float(np.random.uniform(32.0, 48.0)), 1)
            reading["systolic_bp"] = round(float(np.random.uniform(75.0, 90.0)), 1)
            reading["diastolic_bp"] = round(float(np.random.uniform(45.0, 58.0)), 1)

    elif anomaly_scenario == "Low_Oxygen_Saturation":
        # Critical hypoxia desaturation
        reading["oxygen_saturation"] = round(float(np.random.uniform(68.0, 86.0)), 1)
        # Body attempts to compensate with higher pulse
        reading["heart_rate"] = round(float(np.random.uniform(115.0, 142.0)), 1)

    elif anomaly_scenario == "Unusual_Temperature":
        # Sepsis fever spike (85% chance) or severe hypothermia (15% chance)
        if random.random() < 0.85:
            reading["body_temperature"] = round(float(np.random.uniform(39.50, 41.50)), 2)
            reading["heart_rate"] = round(float(np.random.uniform(110.0, 135.0)), 1)
        else:
            reading["body_temperature"] = round(float(np.random.uniform(33.00, 34.80)), 2)
            reading["heart_rate"] = round(float(np.random.uniform(50.0, 62.0)), 1)

    elif anomaly_scenario == "Network_Traffic_Burst":
        # Cyber attack: IoMT device infected with botnet or target of DoS flooding
        reading["device_activity_level"] = round(float(np.random.uniform(400.0, 1350.0)), 1)

    elif anomaly_scenario == "Device_Telemetry_Spoofing":
        # Man-in-the-middle or sensor sabotage: physically contradictory values or flatlining
        spoof_type = random.choice(["flatline", "inverted_bp", "impossible_spo2"])
        if spoof_type == "flatline":
            reading["heart_rate"] = 0.0
            reading["systolic_bp"] = 0.0
            reading["diastolic_bp"] = 0.0
            reading["oxygen_saturation"] = 0.0
        elif spoof_type == "inverted_bp":
            # Diastolic greater than Systolic (physically impossible)
            reading["systolic_bp"] = 70.0
            reading["diastolic_bp"] = 120.0
        else:
            # Oxygen saturation exceeding physical ceiling
            reading["oxygen_saturation"] = 125.0

    elif anomaly_scenario == "Rapid_Battery_Drain":
        # Battery exhaustion attack or thermal power fault
        reading["battery_level"] = round(float(np.random.uniform(1.0, 6.0)), 1)
        reading["device_activity_level"] = round(float(np.random.uniform(180.0, 450.0)), 1)

    return reading


def generate_dataset(
    samples_per_device: int = 2000,
    anomaly_rate: float = 0.055,
    random_seed: int = 42
) -> pd.DataFrame:
    """
    Generate synthetic dataset across all configured medical devices.

    Parameters:
    -----------
    samples_per_device: int
        Number of consecutive readings per device (2,000 * 5 devices = 10,000 records).
    anomaly_rate: float
        Proportion of readings that will contain anomalous behavior (~5.5%).
    random_seed: int
        Random seed for full reproducibility.

    Returns:
    --------
    pd.DataFrame
        Complete dataset DataFrame with 10,000 records and 14 columns.
    """
    np.random.seed(random_seed)
    random.seed(random_seed)

    all_records = []
    # Start ~5 days prior to now so historical data is chronological
    start_time = datetime.now() - timedelta(minutes=samples_per_device * 3)

    reading_counter = 1

    for device_id, info in config.DEVICE_PROFILES.items():
        device_type = info["type"]
        current_time = start_time
        battery = 99.5

        for _ in range(samples_per_device):
            # Gradual battery drain with occasional simulated recharging cycles
            battery -= random.uniform(0.015, 0.045)
            if battery < 20.0:
                battery = 98.0  # Device plugged into AC power / battery replaced

            # Determine whether this observation represents an anomaly
            is_anomaly = random.random() < anomaly_rate

            if is_anomaly:
                record = inject_anomaly_reading(device_id, device_type, current_time, battery)
            else:
                record = generate_normal_reading(device_id, device_type, current_time, battery)

            record["reading_id"] = f"REC-{reading_counter:06d}"
            reading_counter += 1
            all_records.append(record)

            # Advance timestamp by 3 minutes for next reading
            current_time += timedelta(minutes=3)

    df = pd.DataFrame(all_records)

    # Establish clean, logical column hierarchy:
    # Identifiers -> Vitals -> Device/Network Metrics -> Ground Truth Labels -> Compliance Flag
    column_order = [
        "reading_id",
        "timestamp",
        "device_id",
        "device_type",
        "heart_rate",
        "systolic_bp",
        "diastolic_bp",
        "oxygen_saturation",
        "body_temperature",
        "device_activity_level",
        "battery_level",
        "is_anomaly",
        "anomaly_type",
        "is_synthetic",
    ]
    df = df[column_order]
    return df


def save_dataset(df: pd.DataFrame, output_path: Path = config.DATA_FILE_PATH) -> Path:
    """Save the generated DataFrame as a CSV file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    return output_path


def print_dataset_report(df: pd.DataFrame, output_path: Path):
    """Print complete statistical and integrity summary of the generated dataset."""
    print("=" * 80)
    print("MEDICAL DEVICE SYNTHETIC DATASET GENERATION REPORT")
    print("=" * 80)
    print(f"[+] Output File Path: {output_path.resolve()}")
    print(f"[+] Total Records (Shape): {df.shape[0]:,} rows x {df.shape[1]} columns")
    print(f"[+] Unique Devices Simulated: {df['device_id'].nunique()}")
    print(f"[+] Devices: {list(df['device_id'].unique())}")
    print(f"[+] Timestamp Range: {df['timestamp'].min()} to {df['timestamp'].max()}")

    print("\n" + "-" * 40)
    print("1. MISSING VALUE AUDIT")
    print("-" * 40)
    missing = df.isnull().sum()
    if missing.sum() == 0:
        print("[PASS] Zero missing values detected across all 14 columns.")
    else:
        print(missing[missing > 0].to_string())

    print("\n" + "-" * 40)
    print("2. GROUND-TRUTH CLASS DISTRIBUTION")
    print("-" * 40)
    counts = df["is_anomaly"].value_counts()
    normal_count = counts.get(0, 0)
    anomaly_count = counts.get(1, 0)
    normal_pct = (normal_count / len(df)) * 100
    anomaly_pct = (anomaly_count / len(df)) * 100
    print(f"Normal Records   (is_anomaly = 0): {normal_count:,} ({normal_pct:.2f}%)")
    print(f"Abnormal Records (is_anomaly = 1): {anomaly_count:,} ({anomaly_pct:.2f}%)")

    print("\n" + "-" * 40)
    print("3. ANOMALY TYPES BREAKDOWN")
    print("-" * 40)
    type_counts = df["anomaly_type"].value_counts()
    for anom_type, count in type_counts.items():
        pct = (count / len(df)) * 100
        print(f" - {anom_type:<28}: {count:>5} ({pct:>5.2f}%)")

    print("\n" + "-" * 40)
    print("4. COMPLIANCE & SYNTHETIC INTEGRITY AUDIT")
    print("-" * 40)
    synthetic_count = df["is_synthetic"].sum()
    print(f"[PASS] Synthetic Flagged Rows: {synthetic_count:,} / {len(df):,} (100.0% compliant)")

    print("\n" + "-" * 40)
    print("5. NUMERICAL FEATURE DESCRIPTIVE STATISTICS")
    print("-" * 40)
    stat_cols = [
        "heart_rate",
        "systolic_bp",
        "diastolic_bp",
        "oxygen_saturation",
        "body_temperature",
        "device_activity_level",
        "battery_level",
    ]
    print(df[stat_cols].describe().round(2).to_string())

    print("\n" + "-" * 40)
    print("6. FIRST 3 SAMPLE RECORDS (HEAD)")
    print("-" * 40)
    print(df.head(3).to_string())

    print("\n" + "-" * 40)
    print("7. FIRST 3 ANOMALY RECORDS (SAMPLE INJECTIONS)")
    print("-" * 40)
    print(df[df["is_anomaly"] == 1].head(3).to_string())
    print("=" * 80)


